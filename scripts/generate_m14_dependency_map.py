"""Generate the M14 owner/dependency map and audit product renderer callers."""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import check_architecture as architecture  # noqa: E402

PRODUCT_ROOTS = ("Editor", "Runtime", "Engine/UI")
CONCRETE_HEADERS = ("Axle/RHISceneRenderer.hpp", "Axle/SceneRenderer.hpp")
CONCRETE_ACCESS = re.compile(r"\b(?:GetRHIRenderer|GetGLRenderer|RHISceneRenderer\s*\*|SceneRenderer\s*\*)")

CONTRACT_OWNERS = {
    "ViewContext": "Engine/Renderer/include/Axle/ViewContext.hpp",
    "IRenderPass / RenderPassScheduler": "Engine/Renderer/include/Axle/RenderPass.hpp",
    "RenderBackendPolicy": "Engine/Renderer/include/Axle/RenderBackendPolicy.hpp",
    "RenderGraph": "Engine/Renderer/include/Axle/RenderGraph.hpp",
    "ResolvedSurface": "Engine/Renderer/include/Axle/ResolvedSurface.hpp",
    "ShaderSurface": "Engine/Renderer/include/Axle/ShaderSurface.hpp",
    "RHIFrameContext": "Engine/RHI/include/Axle/RHI/RHIFrameContext.hpp",
    "RHIViewTargets": "Engine/RHI/include/Axle/RHI/RHIViewTargets.hpp",
    "RHIResourceService": "Engine/RHI/include/Axle/RHI/RHIResource.hpp",
    "LightingService": "Engine/Renderer/include/Axle/LightingService.hpp",
    "ReflectionService": "Engine/Renderer/include/Axle/ReflectionService.hpp",
    "GIService": "Engine/Renderer/include/Axle/GIService.hpp",
    "TemporalService": "Engine/Renderer/include/Axle/TemporalService.hpp",
    "PostProcessService": "Engine/Renderer/include/Axle/PostProcessService.hpp",
    "RenderDiagnostics": "Engine/Renderer/include/Axle/RenderDiagnostics.hpp",
    "RenderService": "Engine/Scene/include/Axle/RenderService.hpp",
    "RHISceneRenderer": "Engine/Scene/include/Axle/RHISceneRenderer.hpp (facade/legacy adapter)",
    "SceneRenderer": "Engine/Scene/include/Axle/SceneRenderer.hpp (OpenGL compatibility backend)",
}


def audit_callers() -> dict:
    violations = []
    callers = {}
    for root_name in PRODUCT_ROOTS:
        root = ROOT / root_name
        matches = []
        if not root.exists():
            callers[root_name] = matches
            continue
        for path in sorted(root.rglob("*")):
            if not path.is_file() or path.suffix not in {".h", ".hpp", ".cpp", ".cc", ".cxx"}:
                continue
            text = path.read_text(encoding="utf-8-sig")
            relative = path.relative_to(ROOT).as_posix()
            for header in CONCRETE_HEADERS:
                if header in text:
                    violations.append({"file": relative, "kind": "concrete_renderer_include", "value": header})
            if "RenderService::Get()" in text:
                matches.append(relative)
            if CONCRETE_ACCESS.search(text):
                violations.append({"file": relative, "kind": "concrete_renderer_access", "value": "backend renderer access"})
        callers[root_name] = matches
    return {"product_roots": callers, "violations": violations}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-dir", type=Path,
                        default=ROOT / "docs/milestones/MILESTONE_14_RENDER_ARCHITECTURE")
    args = parser.parse_args()
    config_path = ROOT / "scripts/architecture_rules.json"
    config = json.loads(config_path.read_text(encoding="utf-8"))
    report = architecture.inspect(ROOT, config, ROOT)
    callers = audit_callers()

    allowed_modules = {"Renderer", "Scene", "UI", "Editor", "Runtime", "RHI", "Core"}
    edges = [edge for edge in report["target_links"] + report["source_includes"]
             if edge.get("from_module") in allowed_modules and
             (edge.get("to_module") in allowed_modules or edge.get("to_module") is None)]
    payload = {
        "milestone": "M14",
        "unit": "U8",
        "generated_by": "scripts/generate_m14_dependency_map.py",
        "source_files_scanned": report["source_files_scanned"],
        "cmake_files": len(report["cmake_files"]),
        "contract_owners": CONTRACT_OWNERS,
        "product_caller_audit": callers,
        "dependency_edges": edges,
        "architecture_violations": report["violations"],
    }
    args.output_dir.mkdir(parents=True, exist_ok=True)
    json_path = args.output_dir / "U8_M14_DEPENDENCY_MAP.json"
    md_path = args.output_dir / "U8_M14_DEPENDENCY_MAP.md"
    json_path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    lines = [
        "# M14-U8 Dependency and Owner Map",
        "",
        f"Generated by `{payload['generated_by']}`.",
        "",
        "## Contract owners",
        "",
        "| Contract | Owner |",
        "|---|---|",
    ]
    lines.extend(f"| `{name}` | `{owner}` |" for name, owner in CONTRACT_OWNERS.items())
    lines.extend(["", "## Product caller audit", "", "| Product root | RenderService callers |", "|---|---|"])
    for root, files in callers["product_roots"].items():
        lines.append(f"| `{root}` | {len(files)} |")
    lines.extend(["", "## Boundary result", "", f"- Architecture violations: **{len(report['violations'])}**",
                  f"- Product caller violations: **{len(callers['violations'])}**",
                  f"- Filtered dependency edges: **{len(edges)}**", ""])
    md_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"M14_U8_DEPENDENCY_MAP: {json_path}")
    print(f"Architecture violations: {len(report['violations'])}; caller violations: {len(callers['violations'])}")
    return 1 if report["violations"] or callers["violations"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
